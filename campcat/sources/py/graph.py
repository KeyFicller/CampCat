"""LangGraph flow for the sidecar's conversation.

Moves one turn through the graph: build the request, call the model, run what it
asks for, record it. The conversation itself -- its messages, memory and
screenshots -- lives in `session.py`.
"""

from __future__ import annotations

from typing import Iterator, TypedDict

from langchain_core.messages import AIMessage, HumanMessage, SystemMessage
from langgraph.graph import END, StateGraph

import agent.memorier as memorier
import agent.operator as operator
import agent.reflector as reflector
import agent.scripter as scripter
import agent.solo as solo
import observability
import session
import runner
import subagent
import tools

# The host and both agents use the same per-request model cap.
MAX_MODEL_ROUNDS = runner.MAX_MODEL_ROUNDS


def rounds_of(raw: object) -> int:
    """The per-turn round cap from a request field.

    A JSON bool is an int in Python, and `true` is not a cap. Missing or
    unusable values keep the default the sidecar used before the field existed.
    """
    if isinstance(raw, int) and not isinstance(raw, bool) and raw >= 1:
        return raw
    return MAX_MODEL_ROUNDS

class TurnState(TypedDict, total=False):
    text: str       # request: this turn's instruction
    tools: list     # request: OpenAI tool schemas, generated by the C++ host
    memory: str     # request: long-term notes, read off disk by the host
    messages: list  # built by build_messages
    tool_rounds: int
    turn_mark: str  # built by build_messages: id of the message this turn starts at
    reply: str      # response: model output
    turns: int      # response: turns retained in the conversation
    max_model_rounds: int  # request: per-turn round cap; default MAX_MODEL_ROUNDS
    operator_only: bool  # request: operator alone, screenshot and tap only
    error: str
    interrupted: bool  # the user sent a new message; commit, then stop
    finished: bool  # scripter: a Handoff call ended this handoff
    failure_code: str  # scripter: structured failure of its final handoff


def precheck(state: TurnState) -> dict:
    """A turn needs an instruction; whitespace alone is an empty request.

    Rejected here rather than at the model, so a stray space in the input box
    never turns into a paid round trip.
    """
    session.start_turn()
    runner.reset_fail_counts()
    text = (state.get("text") or "").strip()
    if not text:
        return {"error": "请求为空"}
    # Here, not in `build_messages`: `commit` stores this same text, so the
    # history keeps the sentence the model was actually given. Dropping it from
    # history would put the divergence point at the end of every user turn.
    return {"text": text + session.ASK_IN_CHINESE}


def compact(state: TurnState) -> dict:
    memorier.compact()
    return {}


def build_messages(state: TurnState) -> dict:
    """The model input: prompt, conversation, the last screen, this turn's text."""
    messages: list[object] = [
        SystemMessage(
            content=(solo.prompt() if state.get("operator_only")
                     else operator.operator_prompt())
            + memorier.memory_block(state.get("memory") or "")
        )
    ]
    messages.extend(memorier._paired(session.history()))
    frame = session.latest_frame()
    if frame is not None:
        messages.append(frame)
    mark = session.new_mark("turn")
    session.log_turn(state.get("text", ""), mark)
    messages.append(HumanMessage(content=state.get("text", ""), id=mark))
    return {"messages": messages, "turn_mark": mark}


def invoke(state: TurnState) -> dict:
    """The operator's model turn: every host tool except the scripter's own."""
    host = state.get("tools") or []
    offered = solo.tools(host) if state.get("operator_only") else operator.operator_tools(host)
    return runner.invoke(state, offered)


def run_subgraph(compiled, state: dict, callbacks=None) -> dict:
    """Run `compiled` with callbacks and nothing else of its config.

    `callbacks` wins when the caller has them: a handoff passes the ones bound
    to its own span. Otherwise the parent's are copied. The whole config joins
    the two runs, and a picture coming back then stalls the parent's stream.
    Outside a graph there is no config, and that is fine.

    The context var is cleared for the call. LangGraph merges it into the
    config it was given, so the parent's handler and this span's handler both
    recorded every generation.
    """
    if callbacks is None:
        from langgraph.config import get_config
        try:
            callbacks = get_config().get("callbacks")
        except Exception:  # noqa: BLE001 - outside a graph there is no config
            callbacks = None
    if not callbacks:
        return compiled.invoke(state)
    from langchain_core.runnables.config import var_child_runnable_config
    token = var_child_runnable_config.set(None)
    try:
        return compiled.invoke(state, {"callbacks": callbacks})
    finally:
        var_child_runnable_config.reset(token)


def _run_host_tools(messages: list) -> tuple[list, bool]:
    """Run every tool call on the last message on the host.

    `author_script` is not special here. A handoff tool emitted here reaches
    the host as an unknown tool rather than starting another scripter. The
    bool is true when the user interrupted the batch.
    """
    calls = getattr(messages[-1], "tool_calls", None) or []

    def run_one(call: dict) -> runner.ToolResult:
        return runner.host_result(call.get("name", ""), call.get("args") or {})

    results, pictures, interrupted = runner.run_calls(calls, run_one)
    return session.demote_pictures(messages + results + pictures), interrupted


def run_tools(state: TurnState) -> dict:
    """Run the tool calls the model just asked for, one by one.

    Every call is executed by the host, and a failure is reported back to the
    model as the tool's result rather than raised, so it can correct itself on
    the next round.
    """
    messages = list(state.get("messages") or [])
    calls = getattr(messages[-1], "tool_calls", None) or []
    if calls:
        # Before any of them runs: the device moves when a tool does, and a
        # result can only be written if this process lives to see it.
        session.log_intent(messages[-1])
    # The pictures are held back and appended after every result, never between
    # them. Once a round asks for more than one tool, a user turn wedged in
    # mid-way makes the provider read the round as having answered only the
    # calls before it and reject the whole request (400 "insufficient tool
    # messages following tool_calls message").
    host_tools = state.get("tools") or []

    def run_one(call: dict) -> runner.ToolResult:
        name = call.get("name", "")
        args = call.get("args") or {}
        if state.get("operator_only") and name not in solo.SOLO:
            # Not offered this turn, so this is the model calling from the
            # prompt alone. Refused rather than run: a stray call must not
            # start the scripter or drive the device behind the sample.
            return runner.ToolResult(
                "error: 这一轮只能用 " + ", ".join(sorted(solo.SOLO))
                + "；不能用 " + name, error_code="operator_only")
        if name == operator.AUTHOR_SCRIPT_NAME:
            # The screen belongs to the device. A shot the scripter took is the
            # one a later tap in this turn is checked against, so the operator
            # has to see it before that tap. An interrupt inside the scripter
            # propagates, and the calls after this one are filled in by
            # `_run_calls`.
            before = session.latest_shot()
            with subagent.working("scripter",
                                  args.get("goal") or "") as run:
                outcome = scripter.run_scripter(
                    args, host_tools,
                    state.get("max_model_rounds", MAX_MODEL_ROUNDS))
                # After the handoff, where its trajectory and the operator's
                # round count are both still in hand; neither survives the
                # return. The body serves every *later* handoff's scripter; the
                # head rides back on this result, for the operator who is the
                # only one that can change how the next handoff is split.
                content = str(outcome.content)
                head, body = reflector.reflect(
                    scripter.calls(), state.get("tool_rounds", 0), content,
                    handoff_failed=outcome.failed)
                session.add_lessons(body)
                run.settle(content, ok=not outcome.failed)
                content += reflector.directive(head, body)
            pics: list = []
            if session.latest_shot() != before:
                frame = session.latest_frame()
                if frame is not None:
                    pics.append(frame)
            return runner.ToolResult(content, pics, outcome.error_code)
        return runner.host_result(name, args)

    results, pictures, interrupted = runner.run_calls(calls, run_one)
    kept = session.demote_pictures(messages + results + pictures)
    session.log_round(kept)
    out: dict = {"messages": kept,
                 "tool_rounds": state.get("tool_rounds", 0) + 1}
    if interrupted:
        out["interrupted"] = True
    return out


def route_after_tools(state: TurnState) -> str:
    """Another model round, unless the user already sent the next message."""
    if state.get("interrupted"):
        return "commit"
    return "invoke"


def route_after_invoke(state: TurnState) -> str:
    if state.get("error") or state.get("interrupted"):
        return "commit"
    messages = state.get("messages") or []
    calls = getattr(messages[-1], "tool_calls", None) if messages else None
    if not calls:
        return "commit"
    if state.get("tool_rounds", 0) >= state.get("max_model_rounds", MAX_MODEL_ROUNDS):
        return "commit"
    return "run_tools"


def stopped_note(error: object) -> str:
    """One line saying why a turn stopped, short enough to keep."""
    reason = " ".join(str(error).split())
    if len(reason) > 200:
        reason = reason[:199] + "…"
    return "上一轮因 " + reason + " 中断"


def commit(state: TurnState) -> dict:
    """Record the turn.

    A failed turn still keeps the rounds whose calls have results: the device
    already moved, and dropping those leaves the next turn guessing where it
    is. The round that raised is not among them. A turn that failed before any
    round finished is not recorded. Nothing is trimmed here: `compact` owns
    that, and only once the budget is reached.
    """
    own = session.own_since(state.get("messages") or [], state.get("turn_mark"))
    if state.get("error"):
        kept = memorier._paired(own)
        note = stopped_note(state["error"])
        if kept:
            session.log_round(state.get("messages") or [])
            session.append_turn(
                state.get("text", ""),
                kept + [AIMessage(content=note)], mark=state.get("turn_mark"))
        session.log_end(note)
        return {"turns": session.size()}
    session.log_round(state.get("messages") or [])
    session.append_turn(state.get("text", ""), own, mark=state.get("turn_mark"))
    session.log_end("")
    return {"turns": session.size()}


def route_after_precheck(state: TurnState) -> str:
    return "end" if state.get("error") else "compact"


def build_graph():
    graph = StateGraph(TurnState)
    graph.add_node("precheck", precheck)
    graph.add_node("compact", compact)
    graph.add_node("build_messages", build_messages)
    graph.add_node("invoke", invoke)
    graph.add_node("run_tools", run_tools)
    graph.add_node("commit", commit)
    graph.set_entry_point("precheck")
    graph.add_conditional_edges(
        "precheck", route_after_precheck, {"compact": "compact", "end": END}
    )
    graph.add_edge("compact", "build_messages")
    graph.add_edge("build_messages", "invoke")
    graph.add_conditional_edges(
        "invoke",
        route_after_invoke,
        {"run_tools": "run_tools", "commit": "commit"},
    )
    # Another model turn, with the results now in the message list. An
    # interrupt commits what finished and does not call the model again.
    graph.add_conditional_edges(
        "run_tools",
        route_after_tools,
        {"invoke": "invoke", "commit": "commit"},
    )
    graph.add_edge("commit", END)
    return graph.compile()


_GRAPH = None


def stream_turn(state: TurnState,
                out_state: dict) -> Iterator[tuple[bool, str]]:
    """Run the graph, yielding (is_answer, text) and copying the final state.

    (True, delta) is answer text to display. (False, delta) is reasoning text:
    the model is thinking, and the step it belongs to has not answered yet.
    (False, "") is a bare heartbeat -- a chunk with neither. The final state
    lands in `out_state` for `error` and `turns`, which only exist once the run
    is over.
    """
    global _GRAPH
    if _GRAPH is None:
        _GRAPH = build_graph()
    # The loop runs `invoke` once per round, and the UI streams every round, so
    # without a separator the rounds run together on one line until the turn
    # ends and the joined `reply` replaces them. `langgraph_step` is what marks
    # a round: it is the same for every chunk of one model call and rises for
    # the next. Kept in step with the join in `invoke`.
    last_step: object = None
    gap_pending = False
    emitted = False
    with observability.turn("handle-turn", state.get("text", "")) as callbacks:
        for mode, payload in _GRAPH.stream(
            state,
            stream_mode=["messages", "values"],
            config={"callbacks": callbacks},
        ):
            if mode == "values":
                out_state.update(payload)
                continue
            chunk, meta = payload
            # Both the input echo (build_messages) and the summarizer (compact)
            # stream chunks too; only invoke is the answer.
            if meta.get("langgraph_node") != "invoke":
                continue
            step = meta.get("langgraph_step")
            if step != last_step:
                last_step = step
                gap_pending = emitted
            reasoning = session.reasoning_text(chunk)
            if reasoning:
                yield (False, reasoning)
                continue
            text = session.content_text(getattr(chunk, "content", ""))
            if not text:
                yield (False, "")
                continue
            if gap_pending:
                gap_pending = False
                yield (True, "\n\n")
            emitted = True
            yield (True, text)
